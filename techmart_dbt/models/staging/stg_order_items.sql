
WITH source AS (
    SELECT
        PAYLOAD,
        SOURCE_FILE
    FROM TECHMART_DB.RAW.RAW_ORDER_ITEM_PAYLOADS
),

flattened AS (
    SELECT
        source.SOURCE_FILE,
        item.VALUE AS ITEM_JSON
    FROM source,
    LATERAL FLATTEN(
        INPUT => source.PAYLOAD:order_items
    ) AS item
)

SELECT
    TRY_TO_NUMBER(ITEM_JSON:order_id::VARCHAR) AS ORDER_ID,
    TRY_TO_NUMBER(ITEM_JSON:customer_id::VARCHAR) AS CUSTOMER_ID,
    TRY_TO_NUMBER(ITEM_JSON:product_id::VARCHAR) AS PRODUCT_ID,
    ITEM_JSON:product_title::VARCHAR AS PRODUCT_TITLE,
    TRY_TO_NUMBER(ITEM_JSON:quantity::VARCHAR) AS QUANTITY,
    TRY_TO_DECIMAL(ITEM_JSON:price::VARCHAR, 12, 2) AS PRICE,
    TRY_TO_DECIMAL(ITEM_JSON:line_total::VARCHAR, 12, 2) AS LINE_TOTAL,
    TRY_TO_DECIMAL(ITEM_JSON:discount_percentage::VARCHAR, 10, 2) AS DISCOUNT_PERCENTAGE,
    TRY_TO_DECIMAL(ITEM_JSON:discounted_total::VARCHAR, 12, 2) AS DISCOUNTED_TOTAL,
    SOURCE_FILE
FROM flattened
