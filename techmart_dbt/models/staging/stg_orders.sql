
WITH source AS (
    SELECT
        PAYLOAD,
        SOURCE_FILE
    FROM TECHMART_DB.RAW.RAW_ORDER_PAYLOADS
),

flattened AS (
    SELECT
        source.SOURCE_FILE,
        cart.VALUE AS ORDER_JSON
    FROM source,
    LATERAL FLATTEN(
        INPUT => source.PAYLOAD:carts
    ) AS cart
)

SELECT
    TRY_TO_NUMBER(ORDER_JSON:id::VARCHAR) AS ORDER_ID,
    TRY_TO_NUMBER(ORDER_JSON:userId::VARCHAR) AS CUSTOMER_ID,
    TRY_TO_DECIMAL(ORDER_JSON:total::VARCHAR, 12, 2) AS TOTAL,
    TRY_TO_DECIMAL(ORDER_JSON:discountedTotal::VARCHAR, 12, 2) AS DISCOUNTED_TOTAL,
    TRY_TO_NUMBER(ORDER_JSON:totalProducts::VARCHAR) AS TOTAL_PRODUCTS,
    TRY_TO_NUMBER(ORDER_JSON:totalQuantity::VARCHAR) AS TOTAL_QUANTITY,
    ORDER_JSON:products AS PRODUCTS_JSON,
    SOURCE_FILE
FROM flattened
