
WITH source AS (
    SELECT
        PAYLOAD,
        SOURCE_FILE
    FROM TECHMART_DB.RAW.RAW_PRODUCT_PAYLOADS
),

flattened AS (
    SELECT
        source.SOURCE_FILE,
        product.VALUE AS PRODUCT_JSON
    FROM source,
    LATERAL FLATTEN(
        INPUT => source.PAYLOAD:products
    ) AS product
)

SELECT
    TRY_TO_NUMBER(PRODUCT_JSON:id::VARCHAR) AS PRODUCT_ID,
    PRODUCT_JSON:title::VARCHAR AS TITLE,
    PRODUCT_JSON:description::VARCHAR AS DESCRIPTION,
    PRODUCT_JSON:category::VARCHAR AS CATEGORY,
    PRODUCT_JSON:brand::VARCHAR AS BRAND,
    TRY_TO_DECIMAL(PRODUCT_JSON:price::VARCHAR, 10, 2) AS PRICE,
    TRY_TO_DECIMAL(PRODUCT_JSON:discountPercentage::VARCHAR, 10, 2) AS DISCOUNT_PERCENTAGE,
    TRY_TO_DECIMAL(PRODUCT_JSON:rating::VARCHAR, 10, 2) AS RATING,
    TRY_TO_NUMBER(PRODUCT_JSON:stock::VARCHAR) AS STOCK,
    PRODUCT_JSON:availabilityStatus::VARCHAR AS AVAILABILITY_STATUS,
    SOURCE_FILE
FROM flattened
