

USE ROLE ACCOUNTADMIN;
USE DATABASE TECHMART_DB;
USE SCHEMA RAW;
USE WAREHOUSE TECHMART_LOADING_WH;


CREATE TABLE IF NOT EXISTS RAW_CUSTOMER_PAYLOADS (
    PAYLOAD VARIANT,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);


COPY INTO RAW_CUSTOMER_PAYLOADS (
    PAYLOAD,
    SOURCE_FILE
)
FROM (
    SELECT
        $1,
        METADATA$FILENAME
    FROM @TECHMART_CUSTOMERS_STAGE
)
FILE_FORMAT = (
    TYPE = JSON
)
ON_ERROR = 'ABORT_STATEMENT';


SELECT
    SOURCE_FILE,
    PAYLOAD:total::NUMBER AS API_TOTAL,
    ARRAY_SIZE(PAYLOAD:users) AS CUSTOMERS_IN_FILE,
    PAYLOAD:users[0]:firstName::VARCHAR
        AS FIRST_CUSTOMER_FIRST_NAME,
    LOADED_AT
FROM RAW_CUSTOMER_PAYLOADS;
